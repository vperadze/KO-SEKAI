"""Turns the opening film's clips into pictures the game can show, and writes the table the game reads.

    art/voice-model/venv/bin/python art/cinematic/prep_cinematic.py      (needs PyAV and Pillow)

Unreal's video players differ per platform and none is known to work in this project on both Linux and Windows,
so the film is not played as video: every shot becomes one 4096x4096 sheet of 640x360 frames, 12 a second, and
KSHUD shows the frames in turn (DrawIntro). The low frame rate and size pass for a worn VHS tape, which is the look.

art/cinematic/raw/<shot>.mp4 -> art/cinematic/T_KS_Cine_<n>.png   (import: art/tools/import_arenas.py)
                             -> unreal/Source/KoSekai/KSCineData.h (rebuild the game after it)
A shot whose clip is missing is left out of the film.
"""
import os
import av
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = os.path.join(HERE, '..', '..', 'unreal', 'Source', 'KoSekai', 'KSCineData.h')
FPS, W, H, SHEET = 12, 640, 360, 4096
COLS, ROWS = SHEET // W, SHEET // H            # 6 x 11 = 66 frames, five and a half seconds
# The film in order: clip name and the words shown under it.
FILM = [
    ('city',      "1987."),
    ('fighters',  "KO-SEKAI. SEVEN FIGHTERS. THE GREATEST GAME NEVER RELEASED."),
    ('cancelled', "CANCELLED. THREE WEEKS BEFORE LAUNCH."),
    ('alley',     "ONE CABINET SURVIVED."),
    ('fists',     "IT HAS WAITED 39 YEARS FOR A CHALLENGER."),
    ('pull',      "INSERT YOURSELF."),
]


def frames(path):
    """The clip's pictures at FPS a second, whatever rate it was made at."""
    out, due = [], 0.0
    with av.open(path) as clip:
        stream = clip.streams.video[0]
        for frame in clip.decode(stream):
            t = float(frame.pts * stream.time_base) if frame.pts is not None else due
            while t >= due - 1e-6 and len(out) < COLS * ROWS:
                out.append(frame.to_image().convert('RGB').resize((W, H), Image.LANCZOS)); due += 1.0 / FPS
    return out


rows = []
for name, caption in FILM:
    path = os.path.join(HERE, 'raw', name + '.mp4')
    if not os.path.exists(path): print('missing', name); continue
    pics = frames(path)
    sheet = Image.new('RGB', (SHEET, SHEET), 'black')
    for i, pic in enumerate(pics): sheet.paste(pic, ((i % COLS) * W, (i // COLS) * H))
    tex = 'T_KS_Cine_%d' % len(rows)
    sheet.save(os.path.join(HERE, tex + '.png'))
    rows.append((tex, len(pics), caption))
    print('%-10s %2d frames  %.1f s  -> %s' % (name, len(pics), len(pics) / FPS, tex))

with open(HEADER, 'w') as f:
    f.write('// Generated by art/cinematic/prep_cinematic.py - do not edit. The opening film: one sheet of frames per shot\n')
    f.write('// (/Game/KS/Cine/<Texture>, KSCineCols frames to a row), how many frames it has, and the words under it.\n#pragma once\n\n')
    f.write('struct FKSCineShot { const TCHAR* Texture; int32 Frames; const TCHAR* Caption; };\n\n')
    f.write('static const float KSCineFps = %d.f;\nstatic const int32 KSCineCols = %d;\n' % (FPS, COLS))
    f.write('static const float KSCineCellU = %d.f / %d.f, KSCineCellV = %d.f / %d.f;\n\n' % (W, SHEET, H, SHEET))
    f.write('static const FKSCineShot KSCineShots[] = {\n')
    for tex, n, caption in rows: f.write('\t{ TEXT("%s"), %d, TEXT("%s") },\n' % (tex, n, caption))
    if not rows: f.write('\t{ TEXT(""), 0, TEXT("") },\n')
    f.write('};\n')
print('%d shots, %.1f s -> %s' % (len(rows), sum(n for _, n, _ in rows) / FPS, os.path.normpath(HEADER)))
